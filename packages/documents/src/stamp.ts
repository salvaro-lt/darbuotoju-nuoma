// Builds the signed PDF: the signers' values drawn onto the original pages and
// a certificate page (who, when, from which document hash) appended at the end.
// pdf-lib is plain JavaScript, so this runs in Convex's default runtime.
import fontkit from "@pdf-lib/fontkit"
import { PDFDocument, rgb, StandardFonts, type PDFFont, type PDFPage } from "pdf-lib"
import { isImageField, type SigningField, type SigningValue } from "./signing"

export interface CertificateSigner {
  role: string
  name: string
  email: string
  openedAt: number | null
  completedAt: number | null
  userAgent: string | null
  signature: string | null
}

export interface CertificateEvent {
  at: number
  text: string
}

export interface StampInput {
  pdf: Uint8Array
  fields: readonly SigningField[]
  /** Values of every signer, keyed by field ID. */
  values: Record<string, SigningValue>
  certificate: {
    title: string
    submissionId: string
    originalSha256: string
    signers: CertificateSigner[]
    events: CertificateEvent[]
    /** e.g. "lt-LT"; dates are printed in UTC with this locale's format. */
    locale: string
    labels: CertificateLabels
  }
  /** A TrueType/OpenType font with the needed glyphs (Lithuanian letters). Without it, Helvetica and letters are transliterated. */
  font?: Uint8Array | null
}

export interface CertificateLabels {
  heading: string
  document: string
  submission: string
  originalHash: string
  signer: string
  email: string
  opened: string
  signed: string
  device: string
  events: string
  footer: string
}

