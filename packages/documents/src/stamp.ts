/** Removes diacritics for the built-in font (WinAnsi has no ą, č, ę, ė, į, š, ų, ū, ž). */
const ascii = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^\x20-\x7e]/g, "?")

function dataUrlBytes(url: string): Uint8Array {
  const b64 = url.slice(url.indexOf(",") + 1)
  const bin = atob(b64)
  const out = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i)
  return out
}

function fitText(font: PDFFont, text: string, maxW: number, maxSize: number): number {
  let size = maxSize
  while (size > 4 && font.widthOfTextAtSize(text, size) > maxW) size -= 0.5
  return size
}

function wrap(font: PDFFont, text: string, size: number, maxW: number): string[] {
  const lines: string[] = []
  for (const para of text.split("\n")) {
    let line = ""
    for (const word of para.split(/\s+/)) {
      const next = line ? `${line} ${word}` : word
      if (font.widthOfTextAtSize(next, size) > maxW && line) {
        lines.push(line)
        line = word
      } else line = next
    }
    lines.push(line)
  }
  return lines
}

export async function stampPdf(input: StampInput): Promise<Uint8Array> {
  const doc = await PDFDocument.load(input.pdf, { ignoreEncryption: true })
  let font: PDFFont
  let bold: PDFFont
  let clean = (s: string) => s
  if (input.font) {
    doc.registerFontkit(fontkit)
    font = await doc.embedFont(input.font, { subset: true })
    bold = font
  } else {
    font = await doc.embedFont(StandardFonts.Helvetica)
    bold = await doc.embedFont(StandardFonts.HelveticaBold)
    clean = ascii
  }
  const pages = doc.getPages()
  const ink = rgb(0.05, 0.1, 0.3)

  for (const f of input.fields) {
    const page = pages[f.page]
    const value = input.values[f.id]
    if (!page || value === undefined || value === "" || value === false) continue
    const { width: W, height: H } = page.getSize()
    const box = { x: f.x * W, y: H - (f.y + f.h) * H, w: f.w * W, h: f.h * H }
    if (isImageField(f.type) && typeof value === "string") {
      const img = await doc.embedPng(dataUrlBytes(value))
      const scale = Math.min(box.w / img.width, box.h / img.height)
      const w = img.width * scale
      const h = img.height * scale
      page.drawImage(img, { x: box.x + (box.w - w) / 2, y: box.y + (box.h - h) / 2, width: w, height: h })
    } else if (f.type === "checkbox") {
      const s = Math.min(box.w, box.h)
      page.drawText("X", { x: box.x + (box.w - s * 0.6) / 2, y: box.y + (box.h - s * 0.7) / 2, size: s * 0.85, font: bold, color: ink })
    } else {
      const text = clean(String(value))
      const size = fitText(font, text, box.w - 2, Math.min(box.h * 0.7, 14))
      page.drawText(text, { x: box.x + 1, y: box.y + (box.h - size) / 2 + size * 0.15, size, font, color: ink })
    }
  }

  const thumbs = addCertificate(doc, font, bold, clean, input.certificate)
  for (const t of thumbs) {
    const img = await doc.embedPng(dataUrlBytes(t.url))
    const scale = Math.min(160 / img.width, 44 / img.height)
    t.page.drawImage(img, { x: t.x, y: t.y, width: img.width * scale, height: img.height * scale })
  }
  return doc.save()
}

/** Lays out the certificate; returns where signature thumbnails go (embedding is async). */
function addCertificate(doc: PDFDocument, font: PDFFont, bold: PDFFont, clean: (s: string) => string, c: StampInput["certificate"]) {
  const thumbs: { page: PDFPage; x: number; y: number; url: string }[] = []
  const A4 = { w: 595.28, h: 841.89 }
  const margin = 48
  const maxW = A4.w - margin * 2
  const muted = rgb(0.4, 0.42, 0.48)
  const fmt = (t: number | null) =>
    t === null ? "—" : `${new Date(t).toLocaleString(c.locale, { timeZone: "UTC", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit" })} UTC`
  let page: PDFPage = doc.addPage([A4.w, A4.h])
  let y = A4.h - margin

  const need = (h: number) => {
    if (y - h < margin + 30) {
      page = doc.addPage([A4.w, A4.h])
      y = A4.h - margin
    }
  }
  const line = (text: string, o: { size?: number; f?: PDFFont; color?: ReturnType<typeof rgb>; indent?: number } = {}) => {
    const size = o.size ?? 9.5
    for (const l of wrap(o.f ?? font, clean(text), size, maxW - (o.indent ?? 0))) {
      need(size + 4)
      page.drawText(l, { x: margin + (o.indent ?? 0), y: y - size, size, font: o.f ?? font, color: o.color ?? rgb(0.1, 0.1, 0.12) })
      y -= size + 4
    }
  }
  const pair = (k: string, v: string) => line(`${k}: ${v}`)

  line(c.labels.heading, { size: 18, f: bold })
  y -= 8
  pair(c.labels.document, c.title)
  pair(c.labels.submission, c.submissionId)
  pair(c.labels.originalHash, c.originalSha256)
  y -= 10

  for (const s of c.signers) {
    need(110)
    page.drawLine({ start: { x: margin, y }, end: { x: A4.w - margin, y }, thickness: 0.5, color: rgb(0.85, 0.86, 0.9) })
    y -= 12
    line(`${c.labels.signer}: ${s.name || "—"} (${s.role})`, { size: 11, f: bold })
    pair(c.labels.email, s.email)
    pair(c.labels.opened, fmt(s.openedAt))
    pair(c.labels.signed, fmt(s.completedAt))
    if (s.userAgent) line(`${c.labels.device}: ${s.userAgent.slice(0, 200)}`, { color: muted, size: 8 })
    if (s.signature) {
      need(52)
      thumbs.push({ page, x: margin, y: y - 46, url: s.signature })
      y -= 52
    }
    y -= 6
  }

  if (c.events.length) {
    y -= 6
    line(c.labels.events, { size: 11, f: bold })
    for (const e of c.events) line(`${fmt(e.at)}  ${e.text}`, { size: 8.5, color: muted })
  }
  for (const l of wrap(font, clean(c.labels.footer), 7, maxW).slice(0, 3).reverse().map((l, i) => ({ l, i })))
    page.drawText(l.l, { x: margin, y: margin / 2 + l.i * 9, size: 7, font, color: muted })
  return thumbs
}

const EVENT_TEXT: Record<"lt" | "en", Record<string, string>> = {
  lt: { created: "Siuntimas sukurtas", sent: "Kvietimas išsiųstas", opened: "Atidarė", completed: "Pasirašė", declined: "Atsisakė", cancelled: "Atšaukta", finalized: "Sugeneruotas", finalize_failed: "Klaida" },
  en: { created: "Submission created", sent: "Invitation sent", opened: "Opened", completed: "Signed", declined: "Declined", cancelled: "Cancelled", finalized: "Generated", finalize_failed: "Error" },
}

/** The signed PDF from raw submission data: labels and event texts by language. */
export async function buildSignedPdfBytes(input: {
  pdf: Uint8Array
  fields: readonly SigningField[]
  values: Record<string, SigningValue>
  font: Uint8Array | null
  certificate: {
    title: string
    submissionId: string
    originalSha256: string
    locale: string
    lang: "lt" | "en"
    signers: CertificateSigner[]
    events: { at: number; kind: string; who: string | null }[]
  }
}): Promise<Uint8Array> {
  const c = input.certificate
  const words = EVENT_TEXT[c.lang]
  return stampPdf({
    pdf: input.pdf,
    fields: input.fields,
    values: input.values,
    font: input.font,
    certificate: {
      title: c.title,
      submissionId: c.submissionId,
      originalSha256: c.originalSha256,
      locale: c.locale,
      labels: CERTIFICATE_LABELS[c.lang],
      signers: c.signers,
      events: c.events.map((e) => ({ at: e.at, text: `${words[e.kind] ?? e.kind}${e.who ? ` · ${e.who}` : ""}` })),
    },
  })
}
