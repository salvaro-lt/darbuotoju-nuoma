import {
  Box,
  Briefcase,
  Building2,
  Calendar,
  ClipboardList,
  Contact,
  FileText,
  Folder,
  GraduationCap,
  Handshake,
  Heart,
  Landmark,
  Layers,
  MapPin,
  Package,
  Rocket,
  ShoppingCart,
  Star,
  Store,
  Tag,
  Target,
  Ticket,
  Truck,
  UserRound,
  Users,
  Wrench,
  type LucideIcon,
} from "lucide-react"

/** Icons an object can use. Stored by name (`crmObjects.icon`); unknown names fall back to a box. */
export const OBJECT_ICONS: Record<string, LucideIcon> = {
  "building-2": Building2,
  "user-round": UserRound,
  users: Users,
  contact: Contact,
  target: Target,
  handshake: Handshake,
  briefcase: Briefcase,
  folder: Folder,
  "file-text": FileText,
  "clipboard-list": ClipboardList,
  calendar: Calendar,
  ticket: Ticket,
  package: Package,
  truck: Truck,
  store: Store,
  "shopping-cart": ShoppingCart,
  landmark: Landmark,
  "graduation-cap": GraduationCap,
  wrench: Wrench,
  rocket: Rocket,
  layers: Layers,
  "map-pin": MapPin,
  tag: Tag,
  star: Star,
  heart: Heart,
  box: Box,
}

export function ObjectIcon({ name, className }: { name: string; className?: string }) {
  const Icon = OBJECT_ICONS[name] ?? Box
  return <Icon className={className} aria-hidden />
}
