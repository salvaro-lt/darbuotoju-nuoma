// Operator entry points for the n8n integration (scripts/n8n-setup.ts).
//
//   npx convex run n8nSetup:_issueAgentKey '{"name":"n8n"}'
//   npx convex run n8nSetup:_revokeOtherAgentKeys '{"name":"n8n","keepApiKeyId":"<apiKeyId>"}'
//
// Issues an agent API key (`dsk_…`) that n8n uses for the app's MCP endpoint
// and `/api/v1/tools/*`, without a human session: the key is created through
// system-core (`createApiKey`, audited) on behalf of its owner, a Super user
// (`ownerEmail`, else the first active user on SUPER_USER_EMAILS). The key's
// effective access is always capped by that owner's current permissions.
// Issuing never revokes anything: the operator first stores the new secret
// (Infisical, n8n credential), then calls `_revokeOtherAgentKeys`, so a failed
// run never leaves n8n without a working key.
//
// Roles: `roleKeys`, else the "n8n agentas" role (created or synced here) that
// holds every subrole of every business module except n8n's own (`n8n:*`): an
// email-triggered workflow must not be able to create or change n8n workflows.
// The built-in Admin role is protected, so a key cannot carry it.
import {
  createApiKey,
  createRole,
  generateApiKeyMaterial,
  isSuperUser,
  normalizeEmail,
  revokeApiKey,
  SystemError,
  toConvexError,
  updateRole,
  type ErrorCode,
  type SystemContext,
} from "@digimuza/system-core/convex"
import { makeFunctionReference } from "convex/server"
import { v } from "convex/values"
import { internalAction, internalMutation, type MutationCtx } from "./_generated/server"
import { system } from "./system"

/** Throws a client-safe error with a stable code. */
function fail(code: ErrorCode, reason: string, operationId: string): never {
  throw toConvexError(new SystemError(code, undefined, { reason, operationId }), operationId)
}

/** The role a key gets when the operator names none. */
export const N8N_ROLE_NAME = "n8n agentas"
const N8N_ROLE_DESCRIPTION = "Automatizacijos per n8n: visi verslo modulių subvaidmenys, išskyrus n8n valdymą (priskiriamas tik n8n API raktui)."
/** Module whose subroles the n8n agent never gets. */
const N8N_MODULE_ID = "n8n"

type Sys = SystemContext

interface StoredKey {
  apiKeyId: string
  prefix: string
  ownerId: string
  roleIds: string[]
}
type StoreArgs = { name: string; ownerEmail?: string; roleKeys?: string[]; prefix: string; hash: string }
// By name, so this file does not depend on a regenerated `_generated/api`.
const storeAgentKeyRef = makeFunctionReference<"mutation", StoreArgs, StoredKey>("n8nSetup:_storeAgentKey")

/** The key owner: `ownerEmail` (must be Super), else the earliest active Super user. */
async function findOwner(sys: Sys, ownerEmail: string | undefined): Promise<string> {
  const emails = ownerEmail ? [normalizeEmail(ownerEmail)] : [...sys.superEmails]
  const candidates = []
  for (const email of emails) for (const user of await sys.store.findBy("users", "email", email)) if (isSuperUser(sys, user)) candidates.push(user)
  candidates.sort((a, b) => a.createdAt - b.createdAt)
  const owner = candidates[0]
  if (!owner) return fail("NOT_FOUND", ownerEmail ? "owner_not_super" : "no_active_super_user", sys.operationId)
  return owner.key
}

/** Finds or creates the "n8n agentas" role and keeps it at every business-module subrole except `n8n:*`. */
async function ensureN8nRole(ctx: MutationCtx, sys: Sys, actor: { kind: "user"; userId: string }): Promise<string> {
  const business = new Set((await ctx.db.query("modules").collect()).filter((m) => m.kind === "business" && m.present).map((m) => m.key))
  const subroleIds = (await ctx.db.query("subroles").collect())
    .filter((s) => !s.archived && business.has(s.moduleId) && s.moduleId !== N8N_MODULE_ID && !s.key.startsWith(`${N8N_MODULE_ID}:`))
    .map((s) => s.key)
    .sort()
  if (subroleIds.length === 0) fail("CONFLICT", "no_business_subroles", sys.operationId)
  const existing = (await ctx.db.query("roles").collect()).find((r) => r.name === N8N_ROLE_NAME && !r.archived && !r.protected)
  if (!existing) return (await createRole(sys, actor, { name: N8N_ROLE_NAME, description: N8N_ROLE_DESCRIPTION, subroleIds })).roleId
  const current = (await sys.store.findBy("roleSubroles", "roleId", existing.key)).map((r) => r.subroleId).sort()
  if (current.join() !== subroleIds.join()) await updateRole(sys, actor, existing.key, { name: existing.name, subroleIds })
  return existing.key
}

/** Writes the key (material generated by `_issueAgentKey`). Revokes nothing; see `_revokeOtherAgentKeys`. */
export const _storeAgentKey = internalMutation({
  args: { name: v.string(), ownerEmail: v.optional(v.string()), roleKeys: v.optional(v.array(v.string())), prefix: v.string(), hash: v.string() },
  handler: async (ctx, a): Promise<StoredKey> => {
    const { sys } = await system.context(ctx)
    const name = a.name.trim()
    const actor = { kind: "user" as const, userId: await findOwner(sys, a.ownerEmail) }
    try {
      const roleIds = a.roleKeys?.length ? a.roleKeys : [await ensureN8nRole(ctx, sys, actor)]
      const { apiKeyId, prefix } = await createApiKey(sys, actor, { name, roleIds }, { prefix: a.prefix, hash: a.hash })
      return { apiKeyId, prefix, ownerId: actor.userId, roleIds }
    } catch (e) {
      // Same client-safe error shape as system functions.
      throw toConvexError(e, sys.operationId)
    }
  },
})

/**
 * Issues an n8n agent key. Returns the secret once (store it as
 * N8N_AGENT_API_KEY in Infisical); only its hash is kept.
 */
export const _issueAgentKey = internalAction({
  args: { name: v.string(), ownerEmail: v.optional(v.string()), roleKeys: v.optional(v.array(v.string())) },
  handler: async (ctx, a): Promise<StoredKey & { secret: string }> => {
    const m = await generateApiKeyMaterial()
    const res = await ctx.runMutation(storeAgentKeyRef, { ...a, prefix: m.prefix, hash: m.hash })
    return { ...res, secret: m.secret }
  },
})

/**
 * After the new secret is stored: revokes every other active key named `name`
 * owned by the same owner as `keepApiKeyId`. Keys of other owners are untouched.
 */
export const _revokeOtherAgentKeys = internalMutation({
  args: { name: v.string(), keepApiKeyId: v.string() },
  handler: async (ctx, a): Promise<{ revoked: string[] }> => {
    const { sys } = await system.context(ctx)
    const name = a.name.trim()
    const keep = await sys.store.get("apiKeys", a.keepApiKeyId)
    if (!keep || keep.name !== name || keep.purpose !== undefined || keep.revokedAt !== undefined) return fail("NOT_FOUND", "keep_key_not_active", sys.operationId)
    const actor = { kind: "user" as const, userId: keep.ownerId }
    try {
      const revoked: string[] = []
      for (const key of await sys.store.findBy("apiKeys", "ownerId", keep.ownerId)) {
        if (key.key === keep.key || key.name !== name || key.purpose !== undefined || key.revokedAt !== undefined) continue
        await revokeApiKey(sys, actor, key.key)
        revoked.push(key.key)
      }
      return { revoked }
    } catch (e) {
      throw toConvexError(e, sys.operationId)
    }
  },
})
